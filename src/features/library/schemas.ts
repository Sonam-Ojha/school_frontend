import { z } from 'zod';

import { isEncodable } from '@/lib/barcode';
import { optionalText } from '@/lib/validation';

import { MAX_COPIES_PER_BATCH, MAX_RENEWALS } from './constants';

/**
 * Validation for the library.
 *
 * Transform-free, like every other module: optional numbers are held as
 * strings and converted in the service, because a numeric input left blank
 * yields `NaN` rather than null.
 */

export const categorySchema = z.object({
  name: z.string().min(2, 'Category name is required').max(80, 'Name is too long'),
  code: z
    .string()
    .min(2, 'A shelving code is required')
    .max(8, 'Keep the code to eight characters')
    .regex(/^[A-Za-z0-9-]+$/, 'Use letters, numbers and hyphens only'),
  description: optionalText(300, 'Description is too long'),
  is_active: z.boolean(),
});

/**
 * ISBN-10 or ISBN-13, with the separators people actually type.
 *
 * The check digit is validated too — a transposed digit produces a
 * syntactically perfect ISBN that belongs to a different book, and catching
 * it at entry is far cheaper than finding it on the shelf.
 */
function isValidIsbn(raw: string): boolean {
  const digits = raw.replace(/[\s-]/g, '').toUpperCase();

  if (/^\d{9}[\dX]$/.test(digits)) {
    const sum = [...digits].reduce((total, character, index) => {
      const value = character === 'X' ? 10 : Number(character);
      return total + value * (10 - index);
    }, 0);
    return sum % 11 === 0;
  }

  if (/^\d{13}$/.test(digits)) {
    const sum = [...digits].reduce(
      (total, character, index) => total + Number(character) * (index % 2 === 0 ? 1 : 3),
      0,
    );
    return sum % 10 === 0;
  }

  return false;
}

export const bookSchema = z.object({
  title: z.string().min(2, 'Title is required').max(200, 'Title is too long'),
  subtitle: optionalText(200, 'Subtitle is too long'),
  author: z.string().min(2, 'Author is required').max(120, 'Author is too long'),
  isbn: z
    .string()
    .refine((value) => value.trim() === '' || isValidIsbn(value), 'That is not a valid ISBN'),
  category_id: z
    .number({ invalid_type_error: 'Select a category' })
    .int()
    .positive('Select a category'),
  publisher: optionalText(120, 'Publisher is too long'),
  edition: optionalText(40, 'Edition is too long'),
  publication_year: z.string().refine((value) => {
    if (value.trim() === '') return true;
    const year = Number(value);
    return Number.isInteger(year) && year >= 1450 && year <= new Date().getFullYear();
  }, 'Enter a year between 1450 and today'),
  language: z.string().min(1, 'Select a language'),
  pages: z.string().refine((value) => {
    if (value.trim() === '') return true;
    const pages = Number(value);
    return Number.isInteger(pages) && pages > 0 && pages <= 20_000;
  }, 'Enter a page count between 1 and 20,000'),
  price: z
    .number({ invalid_type_error: 'Enter the replacement price' })
    .min(0, 'Price cannot be negative')
    .max(1_000_000, 'That price looks wrong'),
  shelf_no: optionalText(40, 'Shelf location is too long'),
  description: optionalText(1000, 'Description is too long'),
});

/**
 * Adding copies.
 *
 * Accession numbers are generated by the API in a run, not typed — a librarian
 * unpacking twelve copies should not have to key twelve unique numbers, and
 * uniqueness is not something a form can guarantee anyway.
 */
export const addCopiesSchema = z.object({
  quantity: z
    .number({ invalid_type_error: 'How many copies?' })
    .int('Enter a whole number of copies')
    .min(1, 'Add at least one copy')
    .max(MAX_COPIES_PER_BATCH, `Add at most ${MAX_COPIES_PER_BATCH} at a time`),
  condition: z.enum(['new', 'good', 'fair', 'poor'], { invalid_type_error: 'Select a condition' }),
  acquired_on: z.string().min(1, 'Acquisition date is required'),
  price: z.number({ invalid_type_error: 'Enter the price paid' }).min(0, 'Price cannot be negative'),
  shelf_no: optionalText(40, 'Shelf location is too long'),
  remarks: optionalText(200, 'Remarks are too long'),
});

export const copySchema = z.object({
  accession_no: z
    .string()
    .min(3, 'An accession number is required')
    .max(24, 'Accession number is too long')
    .refine(isEncodable, 'This cannot be printed as a barcode — use letters, digits and hyphens'),
  status: z.enum(['available', 'issued', 'reserved', 'lost', 'damaged', 'withdrawn']),
  condition: z.enum(['new', 'good', 'fair', 'poor']),
  acquired_on: z.string().min(1, 'Acquisition date is required'),
  price: z.number({ invalid_type_error: 'Enter the price' }).min(0, 'Price cannot be negative'),
  shelf_no: optionalText(40, 'Shelf location is too long'),
  remarks: optionalText(200, 'Remarks are too long'),
});

export const issueSchema = z.object({
  copy_id: z.number({ invalid_type_error: 'Scan a book' }).int().positive('Scan a book'),
  member_type: z.enum(['student', 'teacher'], { invalid_type_error: 'Select a member' }),
  member_id: z.number({ invalid_type_error: 'Select a member' }).int().positive('Select a member'),
  due_on: z.string().min(1, 'A due date is required'),
  remarks: optionalText(200, 'Remarks are too long'),
});

export const returnSchema = z
  .object({
    loan_id: z.number().int().positive(),
    /** A book can come back damaged, or not come back at all. */
    condition: z.enum(['good', 'fair', 'poor', 'lost'], {
      invalid_type_error: 'Select the condition it came back in',
    }),
    /** Collected at the desk as the book is handed over. */
    collect_fine: z.boolean(),
    remarks: optionalText(200, 'Remarks are too long'),
  })
  .refine((data) => data.condition !== 'lost' || data.remarks.trim().length > 0, {
    message: 'Say what happened to it',
    path: ['remarks'],
  });

export const renewSchema = z.object({
  loan_id: z.number().int().positive(),
  remarks: optionalText(200, 'Remarks are too long'),
});

/** Settling a fine — pay what is owed, or write it off with a reason. */
export const finePaymentSchema = z.object({
  loan_id: z.number().int().positive(),
  amount: z
    .number({ invalid_type_error: 'Enter an amount' })
    .min(0.01, 'Enter an amount greater than zero'),
  remarks: optionalText(200, 'Remarks are too long'),
});

export const fineWaiverSchema = z.object({
  loan_id: z.number().int().positive(),
  /** A write-off without a reason is indistinguishable from a mistake. */
  reason: z.string().min(5, 'Say why the fine is being waived').max(200, 'Reason is too long'),
});

export const MAX_RENEWALS_ALLOWED = MAX_RENEWALS;

export type CategoryInput = z.infer<typeof categorySchema>;
export type BookInput = z.infer<typeof bookSchema>;
export type AddCopiesInput = z.infer<typeof addCopiesSchema>;
export type CopyInput = z.infer<typeof copySchema>;
export type IssueInput = z.infer<typeof issueSchema>;
export type ReturnInput = z.infer<typeof returnSchema>;
export type RenewInput = z.infer<typeof renewSchema>;
export type FinePaymentInput = z.infer<typeof finePaymentSchema>;
export type FineWaiverInput = z.infer<typeof fineWaiverSchema>;
