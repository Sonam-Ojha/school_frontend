import { Braces, ChevronDown, Sparkles } from 'lucide-react';
import { Link } from 'react-router-dom';

import { PATHS } from '@/app/router/paths';
import { Alert } from '@/components/ui/Alert';
import { Badge } from '@/components/ui/Badge';
import { Card, CardBody, CardHeader } from '@/components/ui/Card';
import { Skeleton } from '@/components/ui/Skeleton';
import { useDisclosure } from '@/hooks/useDisclosure';
import { formatNumber } from '@/lib/format';

import {
  CAPABILITY_LABELS,
  PROVIDER_STATUS_LABELS,
  PROVIDER_STATUS_TONES,
} from '../constants';
import { useFeatureVector, useIntelligenceProviders } from '../hooks/useAnalytics';
import type { AnalysisKey, FeatureVector, Intelligence } from '../types';
import type { AnalysisParams } from '../services/analyticsService';

interface IntelligencePanelProps {
  analysisKey: AnalysisKey;
  params: AnalysisParams;
  /** The copy the analysis carries. Null until a provider is bound. */
  intelligence: Intelligence | null;
  /** Row and column counts come from the analysis, so the panel can stay shut. */
  summary: Pick<FeatureVector, 'schema_version' | 'feature_names' | 'target'> & {
    rowCount: number;
  };
}

/**
 * The seam a model would plug into, made visible.
 *
 * "AI ready" here is a data contract rather than a promise, and this panel is
 * where that claim is kept honest: it shows exactly what a provider would
 * receive, whether one is bound, and what it added if so. **Nothing in this
 * module generates a prediction.** The statistics on the screens beside it are
 * deterministic and labelled as such; if this panel says no provider is
 * configured, then nothing you are looking at came from a model.
 *
 * The same three states the communication module uses for its channels —
 * ready, not configured, unavailable — because "we could do this but nobody
 * has set it up" is a different message from "this build cannot".
 */
export function IntelligencePanel({
  analysisKey,
  params,
  intelligence,
  summary,
}: IntelligencePanelProps) {
  const { data: providers, isLoading } = useIntelligenceProviders();
  const features = useDisclosure();

  const vector = useFeatureVector(analysisKey, params, features.isOpen);
  const ready = (providers ?? []).filter((provider) => provider.status === 'ready');

  return (
    <Card>
      <CardHeader
        title="Intelligence"
        description="What a model would be given, and what one has added."
        actions={
          <Badge tone={ready.length > 0 ? 'success' : 'neutral'} withDot>
            {ready.length > 0 ? `${ready.length} provider ready` : 'No provider bound'}
          </Badge>
        }
      />

      <CardBody className="space-y-4">
        {intelligence ? (
          <div className="space-y-3 rounded-lg border border-brand-200 bg-brand-50/40 p-3">
            <p className="flex items-center gap-1.5 text-xs font-medium text-brand-800">
              <Sparkles aria-hidden className="size-3.5" />
              Generated by {intelligence.provider}
            </p>

            {intelligence.summary && (
              <p className="text-sm text-slate-800">{intelligence.summary}</p>
            )}

            {intelligence.forecast && intelligence.forecast.length > 0 && (
              <ul className="space-y-1">
                {intelligence.forecast.map((entry) => (
                  <li key={entry.label} className="flex justify-between text-sm">
                    <span className="text-slate-600">
                      {entry.label} <span className="text-slate-400">({entry.horizon})</span>
                    </span>
                    <span className="font-medium text-slate-900">{entry.value}</span>
                  </li>
                ))}
              </ul>
            )}

            {intelligence.recommendations && (
              <ul className="list-inside list-disc space-y-0.5 text-sm text-slate-700">
                {intelligence.recommendations.map((line) => (
                  <li key={line}>{line}</li>
                ))}
              </ul>
            )}
          </div>
        ) : (
          <Alert tone="info" title="Everything here was computed, not predicted">
            No intelligence provider is bound, so every figure on this page came from the
            statistics named under each finding. The contract below is what a provider would
            receive if one were configured — binding it changes no screen.
          </Alert>
        )}

        {/* The providers this build could use, and where each stands. */}
        <div>
          <p className="mb-2 text-xs font-medium text-slate-600">Providers</p>

          {isLoading ? (
            <Skeleton className="h-20 w-full" />
          ) : (
            <ul className="space-y-2">
              {(providers ?? []).map((provider) => (
                <li
                  key={provider.key}
                  className="flex flex-wrap items-start justify-between gap-2 rounded-lg border border-slate-200 p-3"
                >
                  <div className="min-w-0">
                    <p className="text-sm font-medium text-slate-900">{provider.name}</p>
                    <p className="text-xs text-slate-500">{provider.description}</p>

                    <div className="mt-1.5 flex flex-wrap gap-1">
                      {provider.capabilities.map((capability) => (
                        <span
                          key={capability}
                          title={CAPABILITY_LABELS[capability]}
                          className="rounded bg-slate-100 px-1.5 py-0.5 text-[11px] text-slate-600"
                        >
                          {capability}
                        </span>
                      ))}
                    </div>

                    {provider.detail && (
                      <p className="mt-1 text-xs text-slate-400">{provider.detail}</p>
                    )}
                  </div>

                  <div className="flex shrink-0 items-center gap-2">
                    <Badge tone={PROVIDER_STATUS_TONES[provider.status]}>
                      {PROVIDER_STATUS_LABELS[provider.status]}
                    </Badge>
                    {provider.configured_in === 'settings' && provider.status !== 'ready' && (
                      <Link
                        to={PATHS.settingsProfile}
                        className="text-xs font-medium text-brand-700 hover:underline"
                      >
                        Configure
                      </Link>
                    )}
                  </div>
                </li>
              ))}
            </ul>
          )}
        </div>

        {/* The contract itself. */}
        <div className="rounded-lg border border-slate-200">
          <button
            type="button"
            onClick={features.toggle}
            aria-expanded={features.isOpen}
            className="flex w-full items-center justify-between gap-2 px-3 py-2.5 text-left hover:bg-slate-50"
          >
            <span className="flex items-center gap-2 text-sm font-medium text-slate-800">
              <Braces aria-hidden className="size-4 text-slate-400" />
              Feature contract
            </span>

            <span className="flex items-center gap-2">
              <span className="text-xs text-slate-500">
                {formatNumber(summary.rowCount)} rows × {summary.feature_names.length} columns ·
                schema {summary.schema_version}
              </span>
              <ChevronDown
                aria-hidden
                className={`size-4 text-slate-400 transition-transform ${features.isOpen ? 'rotate-180' : ''}`}
              />
            </span>
          </button>

          {features.isOpen && (
            <div className="space-y-3 border-t border-slate-100 p-3">
              <div>
                <p className="text-xs font-medium text-slate-600">Columns</p>
                <div className="mt-1 flex flex-wrap gap-1">
                  {summary.feature_names.map((name) => (
                    <code
                      key={name}
                      className={`rounded px-1.5 py-0.5 text-[11px] ${
                        name === summary.target
                          ? 'bg-brand-100 text-brand-800'
                          : 'bg-slate-100 text-slate-700'
                      }`}
                    >
                      {name}
                    </code>
                  ))}
                </div>
                {summary.target && (
                  <p className="mt-1 text-xs text-slate-400">
                    <code>{summary.target}</code> is the column a model would predict.
                  </p>
                )}
              </div>

              {vector.isLoading ? (
                <Skeleton className="h-32 w-full" />
              ) : vector.data ? (
                <div>
                  <p className="text-xs font-medium text-slate-600">
                    First rows, exactly as a provider would receive them
                  </p>
                  <pre className="mt-1 max-h-64 overflow-auto rounded bg-slate-900 p-3 text-[11px] leading-relaxed text-slate-100">
                    {JSON.stringify(
                      {
                        schema_version: vector.data.schema_version,
                        target: vector.data.target,
                        rows: vector.data.rows.slice(0, 3),
                      },
                      null,
                      2,
                    )}
                  </pre>
                </div>
              ) : null}
            </div>
          )}
        </div>
      </CardBody>
    </Card>
  );
}
